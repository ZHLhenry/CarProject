#!/usr/bin/env python3
"""把同目录的 versions.properties 同步到各工程的 gradle.properties。

为什么不用 versions.gradle.kts + apply(from = ...)：
  独立的 .gradle.kts 脚本要靠 apply 关联才能拿到 Project 接收者，IDE 对这种
  脚本插件的解析不稳定 —— Gradle 命令行正常，编辑器里却整篇爆红，甚至会把
  宿主 build.gradle.kts 里后续的 extra[...] 一并判为 Unresolved。
  gradle.properties 是纯文本，完全不参与脚本分析，IDE 里不可能有红标。

唯一来源是同目录的 versions.properties（人只改这一个文件），
本脚本负责把它的内容写进各工程 gradle.properties 的标记段里。

同步目标不写死在这份脚本里：
  壳工程 CarMapProject + projects.json 的 publishOrder
  + app-builds.json 的 carModels 派生的 Hmi<车型>Project
所以新增车型只改 JSON，脚本自动跟上（工程目录还不存在时跳过并提示）。

本脚本住在 CarMapProject/ 里（与 versions.properties 同目录），
库工程在上一级，通过 BASE 定位。

用法（在 CarMapProject 目录下）：
  ./sync-versions.py           # 同步
  ./sync-versions.py --check   # 只校验，不一致时退出码 1（可挂 CI / pre-commit）
"""
import sys

import pipeline

ROOT = pipeline.ROOT                        # CarMapProject/
BASE = pipeline.BASE                        # carProject/，库工程在这里
SRC = ROOT / "versions.properties"

START = "# ==== automap versions (generated by sync-versions.py, do not edit) ===="
END = "# ==== end automap versions ===="


def projects():
    """同步目标：壳工程自己 + 发布清单里的全部库工程（顺序无关）。"""
    targets = [pipeline.SELF, *pipeline.publish_order()]

    seen, result = set(), []
    for target in targets:
        if target not in seen:
            seen.add(target)
            result.append(target)
    return result


def read_versions():
    """按行读 versions.properties，保持文件里的顺序。"""
    table = {}
    for raw in SRC.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if "=" not in line:
            raise SystemExit(f"{SRC} 行格式错误（应为 artifact=版本）：{raw!r}")
        key, value = line.split("=", 1)
        table[key.strip()] = value.strip()
    if not table:
        raise SystemExit(f"版本表是空的：{SRC}")
    return table


def render_block(table):
    lines = [START]
    lines.extend(f"automap.version.{k}={v}" for k, v in table.items())
    lines.append(END)
    return "\n".join(lines)


def sync_one(project, block, check):
    props = BASE / project / "gradle.properties"
    text = props.read_text(encoding="utf-8") if props.exists() else ""

    if START in text and END in text:
        head, rest = text.split(START, 1)
        _, tail = rest.split(END, 1)
        new_text = head + block + tail
    else:
        if text and not text.endswith("\n"):
            text += "\n"
        sep = "\n" if text else ""
        new_text = text + sep + block + "\n"

    if new_text == text:
        return False
    if not check:
        props.write_text(new_text, encoding="utf-8")
    return True


def main():
    check = "--check" in sys.argv
    table = read_versions()
    block = render_block(table)

    targets = []
    for project in projects():
        if (BASE / project).is_dir():
            targets.append(project)
        else:
            print(f"⚠ 跳过 {project}：目录不存在 {BASE / project}")

    changed = [p for p in targets if sync_one(p, block, check)]

    if check:
        if changed:
            print("以下工程未同步，请执行 ./sync-versions.py：" + ", ".join(changed))
            return 1
        print(f"已同步（{len(table)} 个 artifact × 共 {len(targets)} 个工程）")
        return 0

    print(f"已同步 {len(table)} 个 artifact 到 {len(targets)} 个工程的 gradle.properties")
    for p in changed:
        print("  更新:", p)
    return 0


if __name__ == "__main__":
    sys.exit(main())

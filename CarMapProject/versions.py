#!/usr/bin/env python3
"""AAR 版本管理：改版本表 + 同步进各工程的 gradle.properties（一件事的两个动作）。

唯一来源是同目录的 versions.properties（人只改这一个文件）。
各工程构建时不读它，读的是自己 gradle.properties 里的 automap.version.* 段，
所以「改表」之后必须「同步」，本脚本把两步放在一起，避免忘掉第二步。

为什么不用 versions.gradle.kts + apply(from = ...)：
  独立的 .gradle.kts 脚本要靠 apply 关联才能拿到 Project 接收者，IDE 对这种
  脚本插件的解析不稳定 —— Gradle 命令行正常，编辑器里却整篇爆红，甚至会把
  宿主 build.gradle.kts 里后续的 extra[...] 一并判为 Unresolved。
  gradle.properties 是纯文本，完全不参与脚本分析，IDE 里不可能有红标。

同步目标不写死：壳工程自己 + projects.json 的 publishOrder
+ app-builds.json 的 carModels 派生的 Hmi<车型>Project，
所以新增车型只改 JSON，脚本自动跟上（工程目录还不存在时跳过并提示）。

用法（在 CarMapProject 目录下）：
  ./versions.py list                       # 查看当前各 artifact 的版本
  ./versions.py bump map-sdk-amap-850 1.0.1        # 只升一个，其余不动
  ./versions.py bump map-api=1.0.2 business=1.0.3  # 一次升多个
  ./versions.py bump --all 1.1.0                   # 全部升到同一版本
  ./versions.py sync                       # 只把版本表同步进各工程（改完 versions.properties 后跑）
  ./versions.py check                      # 只校验是否已同步，不一致退出码 1（CI / pre-commit）

注意：只管 AAR 版本（Maven 坐标），不动 APK 的 versionName / versionCode ——
      那套在 CarMapProject/build.gradle.kts 的 skyBuild.* 里。
"""
import re
import sys

import pipeline

ROOT = pipeline.ROOT                        # CarMapProject/
BASE = pipeline.BASE                        # carProject/，库工程在这里
SRC = ROOT / "versions.properties"

START = "# ==== automap versions (generated by versions.py sync, do not edit) ===="
# 老脚本留下的标记，同步时一并替换掉，避免同一文件里叠出两段
LEGACY_START = "# ==== automap versions (generated by sync-versions.py, do not edit) ===="
END = "# ==== end automap versions ===="

# 壳工程自己也要同步（它读 automap.version.* 解析 AAR 坐标），但它不 publish，
# 所以不在 projects.json 的发布清单里，只有本脚本需要它
SELF = "CarMapProject"

VERSION_RE = re.compile(r"^\d+(\.\d+)+([-.][0-9A-Za-z]+)*$")
ENTRY_RE = re.compile(r"^([A-Za-z0-9._-]+)=(.*)$")


# ---------------------------------------------------------------------------
# 版本表读写
# ---------------------------------------------------------------------------
def read_versions() -> dict:
    """按行读 versions.properties，保持文件里的顺序（跳过注释与空行）。"""
    table = {}
    for raw in SRC.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if "=" not in line:
            raise SystemExit(f"{SRC} 行格式错误（应为 artifact=版本）：{raw!r}")
        key, value = line.split("=", 1)
        table[key.strip()] = value.strip()
    if not table:
        raise SystemExit(f"版本表是空的：{SRC}")
    return table


def set_versions(new_versions: dict) -> set:
    """按 artifact → 新版本 改写版本表（保留注释与原有顺序），返回改动的 artifact。"""
    known = read_versions()
    unknown = [a for a in new_versions if a not in known]
    if unknown:
        raise SystemExit(f"✗ 版本表里没有 artifact：{', '.join(unknown)}（versions.py list 可查看全部名称）")
    invalid = [v for v in new_versions.values() if not VERSION_RE.match(v)]
    if invalid:
        raise SystemExit(f"✗ 版本号格式不对：{', '.join(invalid)}（应形如 1.0.1 / 1.2.0-beta1）")

    lines = []
    for line in SRC.read_text(encoding="utf-8").splitlines():
        m = ENTRY_RE.match(line)
        if m and m.group(1) in new_versions:
            artifact = m.group(1)
            lines.append(f"{artifact}={new_versions[artifact]}")
            print(f"  {artifact:<22} {known[artifact]} → {new_versions[artifact]}")
        else:
            lines.append(line)
    SRC.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return set(new_versions)


# ---------------------------------------------------------------------------
# 同步进各工程
# ---------------------------------------------------------------------------
def projects() -> list:
    """同步目标：壳工程自己 + 发布清单里的全部库工程（顺序无关）。"""
    seen, result = set(), []
    for target in [SELF, *pipeline.publish_order()]:
        if target not in seen:
            seen.add(target)
            result.append(target)
    return result


def render_block(table: dict) -> str:
    lines = [START]
    lines.extend(f"automap.version.{k}={v}" for k, v in table.items())
    lines.append(END)
    return "\n".join(lines)


def sync_one(project: str, block: str, check: bool) -> bool:
    props = BASE / project / "gradle.properties"
    text = props.read_text(encoding="utf-8") if props.exists() else ""

    start = START if START in text else (LEGACY_START if LEGACY_START in text else None)
    if start and END in text:
        head, rest = text.split(start, 1)
        _, tail = rest.split(END, 1)
        new_text = head + block + tail
    else:
        if text and not text.endswith("\n"):
            text += "\n"
        sep = "\n" if text else ""
        new_text = text + sep + block + "\n"

    if new_text == text:
        return False
    if not check:
        props.write_text(new_text, encoding="utf-8")
    return True


def sync_versions(write: bool) -> int:
    table = read_versions()
    block = render_block(table)

    targets = []
    for project in projects():
        if (BASE / project).is_dir():
            targets.append(project)
        else:
            print(f"⚠ 跳过 {project}：目录不存在 {BASE / project}")

    changed = [p for p in targets if sync_one(p, block, check=not write)]

    if not write:
        if changed:
            print("以下工程未同步，请执行 ./versions.py sync：" + ", ".join(changed))
            return 1
        print(f"已同步（{len(table)} 个 artifact × 共 {len(targets)} 个工程）")
        return 0

    print(f"已同步 {len(table)} 个 artifact 到 {len(targets)} 个工程的 gradle.properties")
    for project in changed:
        print("  更新:", project)
    return 0


# ---------------------------------------------------------------------------
# 升版本
# ---------------------------------------------------------------------------
def publish_hint(artifact: str) -> str:
    project = pipeline.artifact_projects().get(artifact)
    if not project:
        return "未识别所属工程，请手工 publish（可在 projects.json 补 artifacts）"
    return f"(cd ../{project} && ./gradlew publish)"


def bump(args: list) -> int:
    table = read_versions()

    if not args:
        return usage()
    if args[0] == "--all":
        if len(args) != 2:
            return usage()
        print("全部升级：")
        changes = dict.fromkeys(table, args[1])
    elif len(args) == 2 and "=" not in args[0]:
        print("单模块升级：")
        changes = {args[0]: args[1]}
    else:
        print("按表升级：")
        changes = {}
        for pair in args:
            if "=" not in pair:
                print(f"✗ 参数无法解析：{pair}", file=sys.stderr)
                return usage()
            artifact, version = pair.split("=", 1)
            changes[artifact] = version

    affected = set_versions(changes)

    # 版本表改了不等于各工程改了：立刻同步，否则构建仍按旧版本解析
    print(flush=True)
    code = sync_versions(write=True)
    if code != 0:
        print("✗ 同步失败：请手工执行 ./versions.py sync", file=sys.stderr)
        return code

    print()
    print("只需发布受影响的工程（其余 AAR 不必重发）：")
    for artifact in sorted(affected):
        print(f"  · {artifact}: {publish_hint(artifact)}")

    print()
    print("然后重新打包（壳工程按新版本解析）：")
    print("  ./gradlew :app:assembleDefault        # 默认渠道；全部渠道用 assembleDebug")
    print("全量重发（不打 APK）：./CarMapProject/build-all.py；要 APK 加 --assemble")
    return 0


def usage() -> int:
    print("用法：")
    print("  ./versions.py list")
    print("  ./versions.py bump <artifact> <版本>        例如 bump map-sdk-amap-850 1.0.1")
    print("  ./versions.py bump <artifact>=<版本> ...    例如 bump map-api=1.0.2 business=1.0.3")
    print("  ./versions.py bump --all <版本>")
    print("  ./versions.py sync | check")
    return 1


def main() -> int:
    args = sys.argv[1:]
    if not args or args[0] in ("-h", "--help"):
        return usage()

    command = args[0]
    if command == "sync":
        return sync_versions(write=True)
    if command in ("check", "--check"):
        return sync_versions(write=False)
    if command in ("list", "--list"):
        for artifact, version in read_versions().items():
            print(f"{artifact} = {version}")
        return 0
    if command == "bump":
        return bump(args[1:])

    print(f"✗ 未知子命令：{command}", file=sys.stderr)
    return usage()


if __name__ == "__main__":
    sys.exit(main())
